  @baseMethod
  def cdf(self, *args, **kwargs) -> float:
    cls = type(self)
    try:
      _ = getattr(cls.pdf, '__base_method__')
    except AttributeError:
      pass
    else:
      raise MissingVariable(self, 'pdf', Func)

